"""Reproducible synthetic platform input, NOT the Member 2 historical scenario."""
import hashlib
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

from backend.contracts import Assumption, Flight, Infrastructure, Reservation, Resource, RulesConfig, Scenario
from backend.engine.scenarios import export_scenario

PROJECT = "00000000-0000-0000-0000-000000000010"


def build_fixture():
    start = datetime(2015, 1, 1, 16, tzinfo=timezone.utc)  # 08:00 PST
    end = start + timedelta(hours=2)
    resources = [Resource(resource_id="28L", kind="RUNWAY", dependent_runway_ids=["28R"]),
                 Resource(resource_id="28R", kind="RUNWAY", dependent_runway_ids=["28L"]),
                 Resource(resource_id="GSE-POOL", kind="EQUIPMENT", capacity=2)]
    flights = []
    checksum = hashlib.sha256(b"airport-platform-synthetic-fixture-v1-seed-2026").hexdigest()

    def assumption(value, unit):
        return Assumption(value=value, unit=unit, source_type="SYNTHETIC",
                          explanation="Declared platform fixture parameter; not historical or certified")

    for i in range(24):
        arrival = i % 2 == 0
        gate, crew = f"G{i:02}", f"CREW-{i:02}"
        resources.extend([Resource(resource_id=gate, kind="GATE", compatible_categories=["MEDIUM", "HEAVY"]),
                          Resource(resource_id=crew, kind="CREW", available_from_utc=start,
                                   available_until_utc=end + timedelta(hours=4), max_work_seconds=8 * 3600)])
        for runway in ("28L", "28R"):
            resources.append(Resource(resource_id=f"TX-{runway}-{gate}", kind="TAXIWAY",
                                      node_from=runway, node_to=gate, minimum_traversal_seconds=120))
        movement = start + timedelta(minutes=10 + 4 * i)
        flights.append(Flight(flight_id=f"{checksum[:16]}:{i+1}", source_row_id=f"{checksum}:{i+1}",
            airline="DEMO", flight_number=str(100 + i), tail_number=f"SYN-{i:03}",
            origin="LAX" if arrival else "SFO", destination="SFO" if arrival else "LAX",
            scheduled_gate_departure_utc=movement - timedelta(hours=1) if arrival else movement - timedelta(minutes=3),
            scheduled_gate_arrival_utc=movement + timedelta(minutes=4) if arrival else movement + timedelta(hours=1),
            state="SCHEDULED", plan=None, assumptions={"wake_category": assumption("MEDIUM", "category"),
                "latest_safe_arrival_utc": assumption((movement + timedelta(minutes=70)).isoformat(), "UTC"),
                "gate_id": assumption(gate, "resource_id"), "crew_id": assumption(crew, "resource_id"),
                "equipment_id": assumption("GSE-POOL", "resource_id")}))
    # Outside-window occupant demonstrates nonempty initial state and immutable occupancy buffers.
    initial = [Reservation(reservation_id="initial-gate-occupancy", resource_id="G23", flight_id="BUFFER-OCCUPANT",
                           kind="GATE", starts_at_utc=start - timedelta(minutes=15),
                           ends_at_utc=start + timedelta(minutes=5))]
    scenario = Scenario(scenario_id="sfo-synthetic-v1", project_id=PROJECT, airport_iata="SFO",
        timezone="America/Los_Angeles", seed=2026, start_utc=start, end_utc=end,
        source_manifest={"source_type": "SYNTHETIC", "fixture_checksum": checksum,
            "description": "24 synthetic flight legs for Member 1 integration; not sourced airport geometry",
            "traffic_window_minutes": 120, "initialization_buffer_minutes": 15,
            "recovery_buffer_minutes": 240, "historical_coverage": False,
            "limitations": ["No passenger connections or overtime model", "Taxi time is a declared proxy",
                            "Dedicated synthetic crews; ground equipment serves both movement directions"]},
        rules_config=RulesConfig(), flights=flights,
        infrastructure=Infrastructure(resources=resources, source_type="SYNTHETIC", effective_date="2015-01-01",
            coverage_limits=["Schematic dependent runway pair 28L/28R, not a verified SFO diagram",
                             "24 declared gates and direct taxi segments", "No real-world safety certification"]),
        initial_occupancy=initial)
    return scenario


def main():
    scenario = build_fixture()
    export_scenario(scenario, Path("fixtures/sfo-synthetic-v1.json"))
    # One authoritative fixture generates both JSON and SQL seed. No fake auth accounts.
    document = json.dumps(scenario.model_dump(mode="json"), separators=(",", ":"))
    sql = "-- Generated by python -m scripts.build_fixture. Synthetic only; no users or credentials.\n"
    sql += f"insert into public.projects values ('{PROJECT}','Airport simulation demo') on conflict do nothing;\n"
    sql += f"insert into public.airports values ('{PROJECT}','SFO','{{\"source_type\":\"SYNTHETIC\"}}') on conflict do nothing;\n"
    sql += f"insert into public.scenarios values ('{scenario.scenario_id}','{PROJECT}',$fixture${document}$fixture$::jsonb) on conflict do nothing;\n"
    sql += "insert into public.scenario_flights(scenario_id,flight_id,project_id,document)\n"
    sql += "select scenario_id,f->>'flight_id',project_id,f from public.scenarios,\n"
    sql += "lateral jsonb_array_elements(document->'flights') f where scenario_id='sfo-synthetic-v1' on conflict do nothing;\n"
    Path("supabase/seed.sql").write_text(sql, encoding="utf-8")
    print(f"Published {len(scenario.flights)} synthetic flights, contract {scenario.schema_version}")


if __name__ == "__main__":
    main()
